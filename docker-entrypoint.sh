#!/bin/sh
# Скрипт запуска внутри контейнера приложения.
# 1. Применяет схему Prisma к базе данных (создаёт таблицы)
# 2. Заполняет базу тестовыми данными (не критично при ошибке)
# 3. Запускает dev-сервер Next.js

set -e

echo "==> Применяем схему Prisma к базе данных..."
npx prisma db push

echo "==> Заполняем базу тестовыми данными (если требуется)..."
npx prisma db seed || echo "Пропускаем заполнение (данные уже есть или произошла ошибка)."

echo "==> Запускаем dev-сервер Next.js на порту 3000..."
npm run dev
