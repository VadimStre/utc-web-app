// Промпт для режима «Поиск альтернативных областей применения» (новых рынков) — Этап 5.
// Точный текст промпта из ТЗ, адаптированный под системно-технический промпт с требованием
// вернуть структурированный JSON. Плейсхолдеры заполняются реальными данными записи УТК:
// keyProduct -> Продукт, purpose -> Функция (назначение) + Объект приложения,
// advantages -> Ключевые характеристики + сравнение с ближайшим Конкурентом,
// principle -> Принцип действия.

import type { UTCRecord } from '@/lib/types';

export function buildAltApplicationsPrompt(record: UTCRecord): string {
  const product = record.keyProduct || 'не указан';
  const purpose = record.purpose || 'не указано';
  const advantages = record.advantages || 'не указаны';
  const principle = record.principle || 'не указан';

  return (
    `Я хочу, чтобы Ты выступил в роли маркетолога-стратега c профессиональными научными и инженерными знаниями в области данной УТК.\n\n` +
    `В описании УТК указано, что Команда специалистов разработала:\n` +
    `Продукт: ${product}\n` +
    `Функция (назначение) этого Продукта и Объект приложения Функции Продукта: ${purpose}\n` +
    `Ключевые характеристики Продукта и сравнение с ближайшим Конкурентом (главная отличительная особенность): ${advantages}\n` +
    `Принцип действия Продукта: ${principle}\n\n` +
    `Умение Команды специалистов разрабатывать Продукты, выполняющие Функции в отношении Объектов со значениями Ключевых характеристик Продукта, недостижимых для Конкурентов, с использованием Принципа действия, называется Уникальной технологической компетенцией и является устойчивым конкурентным преимуществом.\n\n` +
    `В целях коммерциализации и диверсификации это умение (Уникальную технологическую компетенцию) Команда специалистов может применять при разработке других Продуктов, использующих аналогичный Принцип действия.\n\n` +
    `Для того, чтобы предложить такие новые Продукты следует подобрать другие Объекты для данной Функции путём обобщения понятия указанного Объекта и поиска подходящих по Принципу действия альтернатив.\n\n` +
    `На следующем шаге, можно поискать другие возможные Функции Продукта, где важен указанный Принцип действия. При этом для новых Функций тоже возможен подбор соответствующих Объектов, как сказано выше.\n\n` +
    `Запрос:\n` +
    `1. Предложи ещё 5 вариантов конкурентоспособных альтернативных Продуктов, основанных на уникальной технологической компетенции Команды специалистов в различных областях применения путём подбора релевантных Объектов приложения указанной Функции Продукта,\n` +
    `2. Кроме того, Предложи 5 вариантов новых придуманных Тобой Продуктов с другими возможными Функциями (назначениями), применяющих указанный Принцип действия Продукта.\n` +
    `2.1. По каждому варианту новых придуманных Тобой Продуктов, предложи ещё по 3 альтернативы Продуктов, основанных на уникальной технологической компетенции Команды в различных областях применения путём подбора 3 релевантных Объектов приложения каждой Функции Продукта.\n\n` +
    `Ответь верни СТРОГО в формате JSON без markdown-обёртки, без пояснений до/после, по следующей схеме:\n` +
    `{\n` +
    `  "alternativeObjects": ["string", "string", "string", "string", "string"],\n` +
    `  "newFunctions": [\n` +
    `    {\n` +
    `      "function": "string (новая придуманная Функция/назначение Продукта)",\n` +
    `      "objects": ["string", "string", "string"]\n` +
    `    }\n` +
    `  ]\n` +
    `}\n` +
    `где "alternativeObjects" — ровно 5 элементов (ответ на пункт 1), а "newFunctions" — ровно 5 элементов (ответ на пункт 2), каждый с полем "objects" из ровно 3 элементов (ответ на пункт 2.1).`
  );
}
